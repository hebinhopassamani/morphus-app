create table public."Menu" (
  id bigint generated by default as identity not null,
  "Label" text null,
  "Url" text null,
  "Icon" text null,
  "Description" text null,
  "Systeam" boolean null,
  "Aplication" text null,
  "MenuId" bigint null,
  "CorporationId" bigint null,
  constraint "Menu_pkey" primary key (id),
  constraint "Menu_CorporationId_fkey" foreign KEY ("CorporationId") references "Corporations" (id),
  constraint "Menu_MenuId_fkey" foreign KEY ("MenuId") references "Menu" (id),
  constraint "Menu_Aplication_check" check (
    (
      ("Aplication" is null)
      or (
        "Aplication" = any (array['M'::text, 'S'::text, 'W'::text])
      )
    )
  )
) TABLESPACE pg_default;