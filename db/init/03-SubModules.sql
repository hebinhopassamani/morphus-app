create table public."SubModules" (
  id bigint generated by default as identity not null,
  "Name" character varying null,
  "Key" character varying null,
  "Description" text null,
  "System" boolean null,
  "ModuleId" bigint null,
  "CorporationId" bigint null,
  constraint "SubModules_pkey" primary key (id),
  constraint "SubModules_CorporationId_fkey" foreign KEY ("CorporationId") references "Corporations" (id),
  constraint "SubModules_ModuleId_fkey" foreign KEY ("ModuleId") references "Modules" (id)
) TABLESPACE pg_default;